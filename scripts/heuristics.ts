// Generates docs/heuristics.md (graph picture, explanations) and docs/heuristics.gaffy (same graph, static gaffy view)
// from the spec below. Code lines: first match of each anchor after its function's definition, so links follow
// the code; rerun `npm run heuristics` after a change.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { toHtmlPre } from '../src/core/grid';
import { GEdge, GNode } from '../src/core/model';
import { buildScene } from '../src/core/scene';
import { DEFAULT_STYLE, glyphSet } from '../src/core/style';
import { emptyDoc, serializeDoc } from '../src/core/viewdoc';
import { STAGES } from '../src/core/rules';
import { USER_STYLE } from '../src/core/style';
import { CALLS, FNS, locate, RULES, UNANCHORED } from './rules';

if (UNANCHORED.length) throw new Error(`scripts/rules.ts: no code anchor for ${UNANCHORED.join(', ')}`);

const ROOT = process.cwd();
const DOC = 'docs/heuristics.md';
const VIEW = 'docs/heuristics.gaffy';
const LINES = 'src/core/rules.lines.ts';



// ---- lines ------------------------------------------------------------------------------------------
const { find, fn, fileOf, defLine, ruleLine, fnOf } = locate(ROOT);

// ---- explanations (docs/heuristics.md) ---------------------------------------------------------------------

// links from docs/ to the code: ../<path>#L<line>
const code = (file: string, line: number) => `[${file.split('/').pop()}:${line + 1}](../${file}#L${line + 1})`;
const body: string[] = [];
const heading = new Map<string, number>();       // rule id => 0-based heading line in the document
const intro = [
    '# gaffy layout heuristics',
    '',
    'Rules that determine the location and ordering of the symbols drawn on the gaffy graph. Generated by `npm run heuristics` from [scripts/heuristics.ts](../scripts/heuristics.ts); the same graph opens in gaffy as [heuristics.gaffy](heuristics.gaffy) (a static view: no language server).',
    '',
    'Structure: a pipeline of stages (reveal => boxes => block layout => placement => settle => routing, then the webview after layout). Inside the stages, decisions choose between rules (`tree_parent_rule`, `item_state`); four rules are orderings rather than steps (h04, h06, h07, h25); two loops repeat at most 3 times (settle inside `buildScene`, save and redraw in the webview).',
    '',
    'Reading the graph: a function calls the functions and rules below it in code order (call line). In the picture and in gaffy, a function opens its code, a rule or decision opens its explanation below; in gaffy, right click a line > Go to Call Site opens the rule\'s code line.',
    '',
    '## Terms',
    '',
    '- **block**: functions grouped in a namspace box.',
    '- **tree parent**: the immediate caller of a function under (`└─>`).',
    '- **offset**: stored displacement in (columns, rows) of a user dragged symbol.',
    '- **unit**: group of symbols that drag together: a function with hanging functions or a namespace and its contents.',
    '',
];

// ---- graph ------------------------------------------------------------------------------------------
const NODE_FILE = (f: string) => `ts:${f}`;
const key = (id: string) => `${NODE_FILE(fileOf(id))}#${id}`;
const module = (f: string) => f.replace(/\.ts$/, '');

function graph(docLines: Map<string, number>): { nodes: Record<string, GNode>; edges: GEdge[] } {
    const nodes: Record<string, GNode> = {};
    const add = (n: GNode) => { nodes[n.key] = n; };
    const dirs = new Set<string>();
    for (const f of new Set([...fn.values()].map((x) => x.file))) {
        const parts = f.split('/').slice(0, -1);
        for (let i = 1; i <= parts.length; i++) dirs.add(parts.slice(0, i).join('/'));
        add({ key: NODE_FILE(f), kind: 'file', name: f.split('/').pop()!.replace(/\.ts$/, ''), qual: '', module: module(f), parent: `dir:${parts.join('/')}`, path: f, line: 0 });
    }
    for (const d of dirs) {
        const up = d.includes('/') ? `dir:${d.slice(0, d.lastIndexOf('/'))}` : null;
        add({ key: `dir:${d}`, kind: 'folder', name: d.split('/').pop()!, qual: '', module: d, parent: up, path: d });
    }
    for (const x of fn.values()) {
        add({ key: key(x.id), kind: 'function', name: x.id, qual: x.id, module: module(x.file), parent: NODE_FILE(x.file), path: x.file, line: x.line, detail: 'code' });
    }
    for (const r of RULES) {
        // boxed with its code; opens its explanation
        add({ key: key(r.id), kind: 'function', name: r.id, qual: r.id, module: module(fileOf(r.in)), parent: NODE_FILE(fileOf(r.in)), path: DOC, line: docLines.get(r.id) ?? 0,
            detail: `${r.title}: code ${fileOf(r.in)}:${ruleLine.get(r.id)! + 1}` });
    }
    const edges: GEdge[] = [];
    for (const [a, b, at] of CALLS) edges.push({ from: key(a), to: key(b), line: find(fileOf(a), at, defLine(a)) });
    for (const r of RULES) {
        edges.push({ from: key(r.in), to: key(r.id), line: ruleLine.get(r.id)! });
        for (const [a, at] of r.also ?? []) edges.push({ from: key(a), to: key(r.id), line: find(fileOf(a), at, defLine(a)) });
    }
    return { nodes, edges };
}

function view(docLines: Map<string, number>) {
    const doc = emptyDoc('heuristics', { seeds: ['render', 'setSide', 'dragUnit', 'runCmd'].map(key), direction: 'out', arrange: 'auto', depthUp: 0, depthDown: 'all' });
    doc.view.static = true;
    doc.graph = graph(docLines);
    doc.explored = Object.fromEntries(Object.keys(doc.graph.nodes).map((k) => [k, 'both' as const]));
    return doc;
}

// ---- write --------------------------------------------------------------------------------------------
// headings first (their lines feed the graph); picture between intro and explanations
/** Switch, alternatives, parameters and control of a rule (src/core/rules.ts), one list item each. */
function settings(r: (typeof RULES)[number]): string[] {
    const out: string[] = [];
    if (r.without) out.push(`- Switch (Rules panel): off: ${r.without}.`);
    if (r.alternatives) out.push(`- Alternatives (Rules panel): ${Object.entries(r.alternatives.choices).map(([k, v]) => `\`${k}\`${k === r.alternatives!.default ? ' (default)' : ''}: ${v}`).join('; ')}.`);
    for (const [n, p] of Object.entries(r.params ?? {})) {
        out.push(`- Parameter \`${r.id}.${n}\` = ${p.value}, range [${p.min}, ${p.max}]: ${p.doc}.`);
    }
    if (r.control) out.push(`- Chosen by: ${r.control}.`);
    return out.length ? [...out, ''] : [];
}

function sections(): string[] {
    const out: string[] = [];
    for (const stage of STAGES) {
        out.push(`## ${stage}`, '');
        for (const r of RULES.filter((x) => x.stage === stage)) {
            heading.set(r.id, out.length);
            out.push(`### ${r.id}`, '', `**${r.title}.** ${r.text}`, '', ...settings(r), `Code: ${code(fileOf(r.in), ruleLine.get(r.id)!)}, in \`${fnOf(r.in)}\`` +
                (r.also ?? []).map(([a, at]) => `; ${code(fileOf(a), find(fileOf(a), at, defLine(a)))}, in \`${a}\``).join('') + '.', '');
        }
    }
    return out;
}
body.push(...sections());
// draw once to measure the picture height (set by the graph), then with the heading lines
const draw = (docLines: Map<string, number>) => {
    const d = view(docLines);
    const sc = buildScene(d, DEFAULT_STYLE);
    const href = (k: string) => {
        const id = k.slice(k.indexOf('#') + 1);
        if (fn.has(id)) return `../${fn.get(id)!.file}#L${fn.get(id)!.line + 1}`;
        return RULES.some((r) => r.id === id) ? `#${id}` : undefined;
    };
    return { d, pre: ['## Pipeline graph', '', '<pre>', toHtmlPre(sc.grid, glyphSet(DEFAULT_STYLE), href, (k) => d.view.seeds.includes(k)), '</pre>', ''] };
};
// heading lines depend on picture height, and node lines (headings) can break layout ties: redraw until stable
const height = (pre: string[]) => pre.join('\n').split('\n').length;
let final = draw(new Map());
for (let round = 0; round < 4; round++) {
    const next = draw(new Map([...heading].map(([id, l]) => [id, intro.length + height(final.pre) + l])));
    const same = height(next.pre) === height(final.pre);
    final = next;
    if (same) break;
}
writeFileSync(resolve(ROOT, DOC), [...intro, ...final.pre, ...body].join('\n'));
// style.json schema: appearance keys only (core/style.ts USER_STYLE); Options and the Rules panel set the rest per view
const SCHEMA = 'schemas/style.schema.json';
const schema = JSON.parse(readFileSync(resolve(ROOT, SCHEMA), 'utf8'));
for (const sec of Object.keys(schema.properties)) {
    const allow = USER_STYLE[sec];
    if (!allow) { delete schema.properties[sec]; continue; }
    if (allow !== true && schema.properties[sec].properties) {
        for (const k of Object.keys(schema.properties[sec].properties)) if (!allow.includes(k)) delete schema.properties[sec].properties[k];
    }
}
writeFileSync(resolve(ROOT, SCHEMA), JSON.stringify(schema, null, 2) + '\n');
// code sites per rule for the webview's rule panel and action log (rules.lines.ts)
const sites = RULES.map((r) => {
    const all: [string, number][] = [[fileOf(r.in), ruleLine.get(r.id)! + 1], ...(r.also ?? []).map(([a, at]) => [fileOf(a), find(fileOf(a), at, defLine(a)) + 1] as [string, number])];
    return `    ${r.id}: [${all.map(([f, l]) => `['${f}', ${l}]`).join(', ')}],`;
});
writeFileSync(resolve(ROOT, LINES), ['// generated by `npm run heuristics` (scripts/heuristics.ts): code sites [file, 1-based line] per rule of rules.ts',
    'export const RULE_LINES: Record<string, [string, number][]> = {', ...sites, '};', ''].join('\n'));
writeFileSync(resolve(ROOT, VIEW), serializeDoc(final.d));
console.log(`${DOC}: ${RULES.length} rules, ${fn.size} functions; ${VIEW}; ${LINES}`);
